function [aW,aP,aE,source] = ...
    convection_methodB_1d(mesh,U,k,i)

x = mesh.x(:);

hW = x(i)   - x(i-1);
hE = x(i+1) - x(i);

%------------------------------------------------------------
% METHOD B convection (Eq. 1.19)
%------------------------------------------------------------

dW = -hE/(hW*(hW+hE));

dP = (hE-hW)/(hW*hE);

dE =  hW/(hE*(hW+hE));

%------------------------------------------------------------
% Diffusion
%------------------------------------------------------------

diffW =  2*k/(hW*(hW+hE));

diffE =  2*k/(hE*(hW+hE));

diffP = -(diffW + diffE);

%------------------------------------------------------------
% Assemble
%------------------------------------------------------------

aW = U*dW - diffW;

aP = U*dP - diffP;

aE = U*dE - diffE;

source = 0;

end