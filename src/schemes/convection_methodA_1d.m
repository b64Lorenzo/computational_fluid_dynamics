function [aW,aP,aE,source] = ...
    convection_methodA_1d(mesh,U,k,i)

x = mesh.x(:);

hW = x(i)   - x(i-1);
hE = x(i+1) - x(i);

%------------------------------------------------------------
% METHOD A convection (Eq. 1.18)
%------------------------------------------------------------

dW = -1/(hW+hE);

dP = (hE-hW)/(hW*hE);

dE =  1/(hW+hE);

%------------------------------------------------------------
% Diffusion (Eq. 1.20)
%------------------------------------------------------------

diffW =  2*k/(hW*(hW+hE));

diffE =  2*k/(hE*(hW+hE));

diffP = -(diffW + diffE);

%------------------------------------------------------------
% Assemble
%------------------------------------------------------------

aW = U*dW - diffW;

aP = U*dP - diffP;

aE = U*dE - diffE;

source = 0;

end
