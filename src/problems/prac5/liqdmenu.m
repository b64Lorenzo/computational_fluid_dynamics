% LIQDMENU liquid plot control menu
%         LIQDMENU defines the control menu to plot the liquid configuration.
%         Automatic adjustment to Matlab versions; in particular the major graphics step from R2014a to R2014b.
%         Options:
%           Check how many data files are available
%           Select the number of the data file to be plotted
%           Select variable to be plotted
%           Select between color and contour plots
%           Manually override colorrange
%           Manually override vector scaling
%           Edit the title of the plot
%           Animate a user-specified selection of these data as a movie
%           Export movie as mat-file, mpg-file or set of jpg-files
%           Plot variables along cross-sections
%           Start-up streamline display (still under command-window control)
%           Display the geometry 
%           Plot streamfunction and vorticity (if available)
%           Export any plots as a user-named printfile (*.epsc or *.jpg)

%           Filename: liqdmenu.m
%           Date    : 27 March 1999 
%           Last change: January 2016 
%           Author  : A.E.P. Veldman

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%
% Calling sequence:
%
%      m-file                input files      output files
%
% liqdmenu.m                 uvpf####.dat
%    |
%    |-- liqdplot.m          config.dat       *.mpg
%    |                       uvpf####.dat     *.mat
%    |                       (humi####.dat)
%    |                                        *.jpg
%    |     
%    |-- xplot.m             config.dat
%    |                       uvpf####.dat
%    |                       (humi####.dat)
%    |
%    |-- liqprint.m                           *.eps
%    |                                        *.jpg 
%    |
%    |-- strmplot.m          stream.out       traces.mat
%    |      |                (traces.mat)
%    |      |-- geoplot.m    config.dat
%    |
%    |-- geoplot.m           config.dat
%    |
%    |-- psiomega.m          config.dat
%                            psiomega.dat
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Changes
% March 2001: (MTD)
%     -Multiple plot figures support;
%     -Velocity vectors switched on/off separately;
%     -Relative or absolute scaling of velocity vectors;
%     -A probe button is added;
%     -Hor./vert. velocity added for surface/contour plots;
%     -Absolute velocity added for X/Y-plot;
%     -AVI support added for Matlab6;
%     -Matlab6 bug fixed: getframe and movie grab/display in whole
%                         figure instead of axes;
%     -Directory-frame added at bottom of menu;
%     -Right clicking on '??' counts only new data files;
%     -Right clicking on '<' selects plot 1;
%     -Right clicking on '>' selects last new plot;
%     -'LIVE' button added for live animations (interruptible!);
%     -Variables can be set to omit parts of the menu;
%     -humidity data added to uvpf####.dat instead of humi####.dat;
%     -A 'keepzoom' button for fixing the focus between successive plots;
%
% To-do list
%     -Read gzip-ed data files;
%     -Mirroring in both directions;
%     -Adding contourplots to surface plots;
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

